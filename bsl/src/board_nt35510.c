static int s_ready;
static uint16_t s_id;

static void nt35510_set_cursor(uint16_t x, uint16_t y)
{
    /* 列起点：高字节写 0x2A00、低字节写 0x2A01；页起点同理 0x2B00/0x2B01。
     * 窗口终点在初始化表里已设成整屏，这里只动起点（与原厂 lcd_set_cursor 一致）。 */
    bsl_lcd_8080_cmd(0x2A00);
    bsl_lcd_8080_data((uint16_t)(x >> 8));
    bsl_lcd_8080_cmd(0x2A01);
    bsl_lcd_8080_data((uint16_t)(x & 0xFFU));
    bsl_lcd_8080_cmd(0x2B00);
    bsl_lcd_8080_data((uint16_t)(y >> 8));
    bsl_lcd_8080_cmd(0x2B01);
    bsl_lcd_8080_data((uint16_t)(y & 0xFFU));
}

