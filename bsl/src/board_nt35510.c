uint16_t board_nt35510_id(void)
{
    uint16_t hi;

    /* 读 ID 前必须发厂家秘钥，否则 NT35510 不应答（读到 0x0000）。 */
    bsl_lcd_8080_cmd(0xF000);
    bsl_lcd_8080_data(0x0055);
    bsl_lcd_8080_cmd(0xF001);
    bsl_lcd_8080_data(0x00AA);
    bsl_lcd_8080_cmd(0xF002);
    bsl_lcd_8080_data(0x0052);
    bsl_lcd_8080_cmd(0xF003);
    bsl_lcd_8080_data(0x0008);
    bsl_lcd_8080_cmd(0xF004);
    bsl_lcd_8080_data(0x0001);

    bsl_lcd_8080_cmd(0xC500);
    hi = bsl_lcd_8080_read();
    bsl_lcd_8080_cmd(0xC501);
    s_id = (uint16_t)(((uint32_t)hi << 8) | bsl_lcd_8080_read());

    /* 0xC501 对 NT35510 是读 ID 低字节，对 1963 之类是软复位指令：不等这 5 ms，
     * 后面的初始化表会在芯片复位过程中打空。原厂注释就是这条。 */
    HAL_Delay(5U);
    return s_id;
}

bsl_err_t board_nt35510_init(uint32_t expect_id)
{
    unsigned i;
    uint16_t id;

    s_ready = 0;
    s_id = 0U;

    if (bsl_lcd_8080_init() != BSL_OK) {
        return BSL_ERR_IO;
    }

    id = board_nt35510_id();
    if (id != (uint16_t)expect_id) {
        /* 读到 0 说明总线/引脚不对；读到别的值说明插的不是这块屏。
         * 两种都在返回码里分开：调用方（POST）把实际 ID 打出来。 */
        return (id == 0U) ? BSL_ERR_IO : BSL_ERR_NOSUPPORT;
    }

    for (i = 0U; i < NT35510_INIT_COUNT; i++) {
        bsl_lcd_8080_cmd(s_init[i].reg);
        bsl_lcd_8080_data(s_init[i].val);
    }

    /* 睡眠退出 + 等 120 µs + 开显示（原厂在表后单独发这两条）。 */
    bsl_lcd_8080_cmd(0x1100);
    HAL_Delay(1U);
    bsl_lcd_8080_cmd(0x2900);

    s_ready = 1;
    return BSL_OK;
}

uint32_t board_nt35510_blit(uint16_t x, uint16_t y, uint16_t w, uint16_t h,
                            const uint16_t *src, uint16_t stride)
{
    const uint16_t *row = src;
    uint16_t yy;
    uint32_t written = 0U;

    if (s_ready == 0 || src == NULL || w == 0U || h == 0U) {
        return 0U;
    }
    for (yy = 0U; yy < h; yy++) {
        nt35510_set_cursor(x, (uint16_t)(y + yy));
        bsl_lcd_8080_cmd(0x2C00); /* 写 GRAM */
        bsl_lcd_8080_data_burst(row, w);
        row += stride;
        written += w;
    }
    return written;
}

uint16_t board_nt35510_read_pixel(uint16_t x, uint16_t y)
{
    uint16_t rg;
    uint16_t b;

    if (s_ready == 0) {
        return 0U;
    }
    nt35510_set_cursor(x, y);
    bsl_lcd_8080_cmd(0x2E00); /* 5510 的读 GRAM 指令 */
    (void)bsl_lcd_8080_read(); /* 假读 1：空周期 */
    for (volatile unsigned d = 0U; d < 256U; d++) {
    }
    /* 5510 的 GRAM 读出是 18 位（3 字节）：第一次读到 R|G（各 8 位），
     * 第二次读到 B。原厂 lcd_read_point() 就是这么拼的，并按
     *   R5 = r>>11、G6 = (r&0xFF)>>2、B5 = b>>11
     * 换算回 RGB565。只读一次 16 位会丢掉蓝色低位（现场实测
     * 0x2104 读回 0x2100），看起来像"写没进去"。 */
    rg = bsl_lcd_8080_read();
    for (volatile unsigned d = 0U; d < 256U; d++) {
    }
    b = bsl_lcd_8080_read();
    return (uint16_t)(((rg >> 11) << 11) | (((rg & 0xFFU) >> 2) << 5) | (b >> 11));
}
